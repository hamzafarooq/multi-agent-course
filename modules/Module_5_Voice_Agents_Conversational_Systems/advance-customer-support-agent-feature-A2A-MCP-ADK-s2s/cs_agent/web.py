"""Speech-to-speech (voice) web app for the customer-support agent.

A FastAPI app on its own port (8001) that wires a browser WebSocket to the Gemini Live
voice engine in ``cs_agent/voice.py`` and reuses the shared building blocks (auth, MCP
tools, Mem0, prompts, A2A client). The text CLI (``agent_cli.py``) is untouched.

The single-page UI (cs_agent/static/index.html + static/voice.js) renders every event the
engine emits — the post-hoc Security Judge, each tool call with the SQL it ran, the Live
model's tokens, the Phoenix trace — as a "What happened" panel under each spoken or typed
answer, and ``/architecture`` lights up the system diagram live.

Run it:  ./run.sh voice        (or: python -m cs_agent.web)
Needs: Postgres (:5433), MCP Toolbox (:5001), A2A (:11002/:11003), plus a GOOGLE_API_KEY
whose project has access to the Gemini Live model (see voice.py:VOICE_MODEL).

Browser note: microphone capture requires a secure context — http://127.0.0.1 / localhost
qualifies; a bare LAN IP over http does not (browsers block getUserMedia there).
"""

