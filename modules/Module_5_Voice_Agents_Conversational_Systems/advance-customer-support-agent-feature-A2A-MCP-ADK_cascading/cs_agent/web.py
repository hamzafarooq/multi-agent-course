"""Web frontend for the customer-support cascade agent.

One text pipeline — sanitize -> A2A Security Judge -> ADK agent (+ MCP tools, Mem0) ->
A2A Data Masker — exposed three ways from this FastAPI app:

  * ``POST /api/chat``         one JSON reply (used by scripts / the benchmark)
  * ``POST /api/chat/stream``  the same turn as newline-delimited JSON *events*: every
                               pipeline step, each with its type, latency, Phoenix span,
                               the SQL an MCP tool ran, Gemini's decision and tokens
  * ``/voice/ws``              the voice cascade (cs_agent/voice/router.py): STT, then
                               this exact pipeline, then TTS — emitting the same events

The single-page UI (cs_agent/static/index.html) renders those events as a "What happened"
panel under every answer, and ``/architecture`` lights up the system diagram live.

Run it via:  ./run.sh web      (or: python -m cs_agent.web)
Requires the same services as the CLI: Postgres, MCP Toolbox (:5000), A2A (:10002/:10003).
"""

