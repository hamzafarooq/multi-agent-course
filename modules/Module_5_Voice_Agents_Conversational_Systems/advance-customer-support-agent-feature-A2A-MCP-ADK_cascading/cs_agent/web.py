# --- What each tool *is* (shown in the UI next to every call) ----------------------
def _tool_catalogue() -> dict:
    """MCP tools from mcp_toolbox/tools.yaml: kind, READ/WRITE, the SQL, its params."""
    path = os.path.join(_project_root, "mcp_toolbox", "tools.yaml")
    try:
        with open(path) as f:
            cfg = yaml.safe_load(f)
    except OSError:          # generated by `./run.sh setup`; UI degrades to a plain row
        return {}
    out = {}
    for name, t in cfg["tools"].items():
        stmt = t.get("statement", "").strip()
        out[name] = {
            "kind": "MCP",
            "access": "READ" if stmt.upper().startswith("SELECT") else "WRITE",
            "path": ["Gemini function call", "ADK", "toolbox-core", "MCP tools/call",
                     "Toolbox :5000", "PostgreSQL"],
            "runs": f"{t['kind']} on {t['source']}",
            "statement": stmt,
            "params": [p["name"] for p in t.get("parameters", [])],
        }
    return out


